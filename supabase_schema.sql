-- Profiles policies
create policy "profiles: self or admin read" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "profiles: self update" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Tools policies
create policy "tools: public approved read" on public.tools for select using (status = 'approved' or public.is_admin());
create policy "tools: admin insert" on public.tools for insert to authenticated with check (public.is_admin());
create policy "tools: admin update" on public.tools for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "tools: admin delete" on public.tools for delete to authenticated using (public.is_admin());

-- Submissions policies
create policy "submissions: owner or admin read" on public.submissions for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "submissions: authenticated insert" on public.submissions for insert to authenticated with check (user_id = auth.uid());
create policy "submissions: admin update" on public.submissions for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "submissions: admin delete" on public.submissions for delete to authenticated using (public.is_admin());

-- Reviews policies
create policy "reviews: public read" on public.reviews for select using (true);
create policy "reviews: authenticated insert" on public.reviews for insert to authenticated with check (user_id = auth.uid());
create policy "reviews: owner update" on public.reviews for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "reviews: owner delete" on public.reviews for delete to authenticated using (user_id = auth.uid());

-- Sign In Logs policies
create policy "sign in logs: admin read" on public.sign_in_logs for select to authenticated using (public.is_admin());
create policy "sign in logs: authenticated insert" on public.sign_in_logs for insert to authenticated with check (user_id = auth.uid());

